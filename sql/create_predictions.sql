-- 翌日予想を保存するテーブル
create table if not exists public.predictions (
  id bigint generated by default as identity primary key,
  prediction_day date not null,
  source_through_day date not null,
  shopid text not null,
  slotid text not null,
  name text,
  score numeric(8, 3) not null,
  positive_probability numeric(6, 5),
  grade text,
  reasons jsonb not null default '[]'::jsonb,
  model_version text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint predictions_probability_range
    check (
      positive_probability is null
      or positive_probability between 0 and 1
    ),
  constraint predictions_source_before_target
    check (source_through_day < prediction_day),
  constraint predictions_unique_prediction
    unique (prediction_day, shopid, slotid, model_version)
);

-- 画面からの日付・店舗検索を速くする。
create index if not exists predictions_day_shop_score_idx
  on public.predictions (prediction_day, shopid, score desc);

create index if not exists predictions_day_shop_name_idx
  on public.predictions (prediction_day, shopid, name);

-- Web画面は公開予想を読めるが、書き込みはバッチだけに限定する。
alter table public.predictions enable row level security;

revoke all on table public.predictions from anon, authenticated;
grant select on table public.predictions to anon, authenticated;

drop policy if exists "Predictions are publicly readable"
  on public.predictions;

create policy "Predictions are publicly readable"
  on public.predictions
  for select
  to anon, authenticated
  using (true);

comment on table public.predictions is
  '過去データだけを使用して作成した台ごとの翌日予想';

comment on column public.predictions.source_through_day is
  '予想計算に使用した実績データの最終日';

comment on column public.predictions.model_version is
  '予想ロジックを識別し、過去の予想を再現するためのバージョン';
